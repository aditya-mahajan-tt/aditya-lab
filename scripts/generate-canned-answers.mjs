#!/usr/bin/env node
/**
 * Regenerates lib/ai/canned-answers.generated.ts (AI_SPEC.md §5) by calling
 * the real /api/ask endpoint for each suggested question — so the cached
 * copy is produced by the exact same guarded, grounded path a live visitor
 * gets, never hand-written. Requires:
 *
 *   1. AI_PROVIDER_API_KEY and AI_MODEL set (Groq — see .env.example).
 *   2. A server running at ASK_LAB_BASE_URL (default localhost:3000) —
 *      `npm run dev` or `npm start` in another terminal, or a deployed URL.
 *
 * Run: npm run ai:generate-canned-answers
 *
 * This list is duplicated from lib/ai/suggested-questions.ts rather than
 * imported — a standalone Node script can't import that project's .ts
 * files without a bundler (see the comment on lib/ai/knowledge.ts for why
 * knowledge derivation itself lives inside the Next app instead of a
 * script). Six fixed strings, low drift risk; keep the two in sync by hand.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const SUGGESTED_QUESTIONS = [
  "What is Aditya strongest at?",
  "What has he built?",
  "Tell me about the goSTOPS project.",
  "What technologies does he use?",
  "What kind of problems does he enjoy?",
  "Why should I work with him?",
];

const BASE_URL = process.env.ASK_LAB_BASE_URL ?? "http://localhost:3000";
const OUTPUT = resolve(import.meta.dirname, "..", "lib", "ai", "canned-answers.generated.ts");

async function ask(question) {
  const res = await fetch(`${BASE_URL}/api/ask`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ question, history: [] }),
  });
  const data = await res.json();
  if (data.status !== "answered") {
    throw new Error(`"${question}" → status "${data.status}" (server offline, unreachable, or not configured?)`);
  }
  return data.message;
}

console.log(`Generating canned answers against ${BASE_URL} ...\n`);

const answers = {};
for (const question of SUGGESTED_QUESTIONS) {
  process.stdout.write(`  ${question} ... `);
  try {
    answers[question] = await ask(question);
    console.log("ok");
  } catch (err) {
    console.log("FAILED");
    console.error(`\n✖ ${err.message}\n`);
    console.error(
      "Nothing written — a partial/failed regeneration would either leave stale answers\n" +
        "or fabricate content. Fix the server/key and re-run.\n",
    );
    process.exit(1);
  }
}

const contents = `import type { SuggestedQuestion } from "./suggested-questions";

/**
 * Generated by \`npm run ai:generate-canned-answers\` on ${new Date().toISOString()}.
 * Do not edit by hand — re-run the script instead. See AI_SPEC.md §5.
 */
export const CANNED_ANSWERS: Record<SuggestedQuestion, string> = ${JSON.stringify(answers, null, 2)};

export const CANNED_ANSWERS_GENERATED_AT: string | null = ${JSON.stringify(new Date().toISOString())};
`;

writeFileSync(OUTPUT, contents);
console.log(`\n✔ Wrote ${OUTPUT.replace(resolve(import.meta.dirname, ".."), ".")}`);
