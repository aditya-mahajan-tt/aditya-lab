#!/usr/bin/env node
/**
 * Scans /data for unfilled [X_REQUIRED] tokens.
 *
 *  - Development: reports them and regenerates CONTENT_TODO.md. Exit 0.
 *  - Production (NODE_ENV=production or --strict): FAILS. Exit 1.
 *
 * See CLAUDE.md §7. A placeholder must never reach the live site.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const DATA_DIR = join(ROOT, "data");
const TOKEN = /\[[A-Z0-9_]+_REQUIRED\]/g;

const strict = process.argv.includes("--strict") || process.env.NODE_ENV === "production";

const findings = [];

for (const file of readdirSync(DATA_DIR).filter((f) => f.endsWith(".ts"))) {
  const contents = readFileSync(join(DATA_DIR, file), "utf8");
  contents.split("\n").forEach((line, i) => {
    for (const match of line.matchAll(TOKEN)) {
      findings.push({ file, line: i + 1, token: match[0] });
    }
  });
}

const byFile = findings.reduce((acc, f) => {
  (acc[f.file] ??= []).push(f);
  return acc;
}, {});

const md = [
  "# CONTENT_TODO.md",
  "",
  "> Auto-generated by `npm run check:placeholders`. Do not edit by hand.",
  "> Every token below blocks the production build. See CONTENT_INTAKE.md for what each needs.",
  "",
  findings.length === 0
    ? "**No outstanding placeholders. Content is complete.**"
    : `**${findings.length} outstanding placeholder${findings.length === 1 ? "" : "s"}.**`,
  "",
  ...Object.entries(byFile).flatMap(([file, items]) => [
    `## data/${file}`,
    "",
    ...items.map((i) => `- [ ] \`${i.token}\` — line ${i.line}`),
    "",
  ]),
].join("\n");

writeFileSync(join(ROOT, "CONTENT_TODO.md"), md);

if (findings.length === 0) {
  console.log("✔ check:placeholders — no unfilled content tokens");
  process.exit(0);
}

console.log(`\n${findings.length} unfilled content token(s):\n`);
for (const [file, items] of Object.entries(byFile)) {
  console.log(`  data/${file}`);
  for (const i of items) console.log(`    ${String(i.line).padStart(4)}  ${i.token}`);
}
console.log("\nCONTENT_TODO.md regenerated.\n");

if (strict) {
  console.error("✖ Placeholders must not ship to production. Fill them or remove the section.\n");
  process.exit(1);
}

console.log("(dev mode — not failing. Run with --strict to enforce.)\n");
