#!/usr/bin/env node
/**
 * Scans /data for unfilled [X_REQUIRED] tokens and unreviewed
 * [AI_DRAFT_REVIEW] content — the latter is real prose Claude Code drafted
 * from supplied source material (a resume, etc), not Aditya's own words,
 * and must never ship without him reviewing/rewriting it. Same severity as
 * a missing placeholder — see data/schema.ts's DRAFT_MARKER comment.
 *
 *  - Development: reports them and regenerates CONTENT_TODO.md. Exit 0.
 *  - Production (NODE_ENV=production or --strict): FAILS. Exit 1.
 *
 * See CLAUDE.md §7. Neither state must ever reach the live site.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const DATA_DIR = join(ROOT, "data");
const TOKENS = [
  { type: "required", pattern: /\[[A-Z0-9_]+_REQUIRED\]/g },
  { type: "draft", pattern: /\[AI_DRAFT_REVIEW\]/g },
];
// Code, not content — schema.ts defines the token patterns themselves and
// queries.ts is pure logic, so neither should ever be scanned for them.
const EXCLUDE = new Set(["schema.ts", "queries.ts"]);

const strict = process.argv.includes("--strict") || process.env.NODE_ENV === "production";

const findings = [];

for (const file of readdirSync(DATA_DIR).filter((f) => f.endsWith(".ts") && !EXCLUDE.has(f))) {
  const contents = readFileSync(join(DATA_DIR, file), "utf8");
  contents.split("\n").forEach((line, i) => {
    for (const { type, pattern } of TOKENS) {
      for (const match of line.matchAll(pattern)) {
        findings.push({ file, line: i + 1, token: match[0], type });
      }
    }
  });
}

const byFile = findings.reduce((acc, f) => {
  (acc[f.file] ??= []).push(f);
  return acc;
}, {});

const requiredCount = findings.filter((f) => f.type === "required").length;
const draftCount = findings.filter((f) => f.type === "draft").length;

const md = [
  "# CONTENT_TODO.md",
  "",
  "> Auto-generated by `npm run check:placeholders`. Do not edit by hand.",
  "> `_REQUIRED` tokens are missing content — see CONTENT_INTAKE.md for what each needs.",
  "> `AI_DRAFT_REVIEW` markers are content Claude Code drafted from supplied source material",
  "> (a resume, etc) — read it, rewrite it in your own words or approve it, then remove the marker.",
  "> Both block the production build.",
  "",
  findings.length === 0
    ? "**No outstanding placeholders or unreviewed drafts. Content is complete.**"
    : `**${requiredCount} missing, ${draftCount} unreviewed draft${draftCount === 1 ? "" : "s"}.**`,
  "",
  ...Object.entries(byFile).flatMap(([file, items]) => [
    `## data/${file}`,
    "",
    ...items.map((i) => `- [ ] ${i.type === "draft" ? "**DRAFT** " : ""}\`${i.token}\` — line ${i.line}`),
    "",
  ]),
].join("\n");

writeFileSync(join(ROOT, "CONTENT_TODO.md"), md);

if (findings.length === 0) {
  console.log("✔ check:placeholders — no unfilled tokens, no unreviewed drafts");
  process.exit(0);
}

console.log(`\n${requiredCount} missing, ${draftCount} unreviewed draft(s):\n`);
for (const [file, items] of Object.entries(byFile)) {
  console.log(`  data/${file}`);
  for (const i of items) {
    console.log(`    ${String(i.line).padStart(4)}  ${i.type === "draft" ? "[DRAFT] " : ""}${i.token}`);
  }
}
console.log("\nCONTENT_TODO.md regenerated.\n");

if (strict) {
  console.error(
    "✖ Placeholders and unreviewed AI drafts must not ship to production. Fill/review them or remove the section.\n",
  );
  process.exit(1);
}

console.log("(dev mode — not failing. Run with --strict to enforce.)\n");
